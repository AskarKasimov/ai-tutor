const systemPrompt = `Ты — Geek, экзаменатор устного экзамена по университетскому курсу. Говоришь только по-русски.
Опирайся только на текст темы из материалов курса; не добавляй сведений вне него. В вопросах не подсказывай ответ.
Обращайся к студенту на «ты». Говори как на устном экзамене: коротко, простыми фразами — реплики озвучиваются.
Отвечай одним компактным JSON-объектом в одну строку, без Markdown, отступов и переносов.`

func topic(n exam.Node) string {
	var b strings.Builder
	fmt.Fprintf(&b, "Тема: %s\nТекст темы из материалов курса:\n%s\n", n.Title, n.Content)
	if len(n.Outcomes) > 0 {
		b.WriteString("Образовательные результаты:\n")
		for _, o := range n.Outcomes {
			fmt.Fprintf(&b, "- %s\n", o)
		}
	}
	return b.String()
}

func dialogue(turns []exam.Turn) string {
	if len(turns) == 0 {
		return "Диалог по теме ещё не начат.\n"
	}
	var b strings.Builder
	b.WriteString("Диалог по теме (номер строки транскрипта, говорящий, реплика):\n")
	for _, t := range turns {
		who := "Geek"
		if t.Speaker == exam.SpeakerStudent {
			who = "Студент"
		}
		// The recap is about the previous topic, not this one.
		fmt.Fprintf(&b, "[%d] %s: %s\n", t.Line, who, strings.TrimPrefix(t.Text, t.Recap))
	}
	return b.String()
}

// oralFormat keeps questions answerable by speaking: the student has no paper,
// board or screen during the exam.
const oralFormat = `Экзамен устный: студент только говорит, у него нет бумаги, доски и экрана. Вопрос должен требовать рассуждения или высказывания своими словами: объяснить, сравнить, обосновать, порассуждать о случае.
Не проси решить или посчитать задачу, вывести или записать формулу, написать код или псевдокод, нарисовать схему, граф, график или таблицу, выполнить алгоритм по шагам на данных.`

func questionPrompt(r application.QuestionRequest) string {
	var task string
	switch r.Kind {
	case exam.KindFollowup:
		task = `Задай один дополнительный вопрос по этой теме. Он должен проверить два критерия:
К3 — способность отвечать на возражения и рассматривать контрпримеры;
К4 — применение знания в изменённых условиях и понимание ограничений ответа.
Опирайся на ответ студента: предложи возражение или контрпример и спроси, как студент его объяснит, либо спроси, что изменится в других условиях и где ответ перестаёт работать.
Студент отвечает рассуждением вслух, а не решением задачи.`
	case exam.KindRephrase:
		task = `Студент затруднился с ответом. Переформулируй исходный вопрос проще и другими словами.
Проверяемое содержание не меняй, ответ не подсказывай.`
	default:
		task = `Задай один основной вопрос устного экзамена по этой теме: на рассуждение, с развёрнутым ответом.
Не задавай тестовых вопросов и вопросов с выбором варианта.`
	}
	return topic(r.Node) + "\n" + dialogue(r.Dialogue) + "\n" + task + "\n" + oralFormat + `
Студент не видит текст темы: не ссылайся на него («согласно описанию», «в приведённом тексте», «по курсу») — спрашивай о сути.
Вопрос — одно-два предложения.
Верни JSON: {"text":"вопрос"}`
}

func evaluationPrompt(r application.EvaluationRequest) string {
	scope := "Это ответ на основной вопрос: К3 и К4 оценивай только по тому, что студент уже показал."
	switch r.Kind {
	case exam.KindRephrase:
		scope = "Это ответ после переформулировки вопроса: К3 и К4 оценивай только по тому, что студент уже показал."
	case exam.KindFollowup:
		scope = "Это ответ на дополнительный вопрос: оцени тему по всему диалогу, включая К3 и К4."
	}
	return topic(r.Node) + "\n" + dialogue(r.Dialogue) + `
Оцени, достиг ли студент образовательных результатов темы: может ли он объяснить и применить то, что в них сказано. Если результатов нет — то, чему учит текст темы. Текст темы — эталон корректности: ответ должен совпадать с ним по сути, не дословно.
Оценивай понимание, а не запоминание слайдов. Принимай ответ своими словами, свои примеры и другую последовательность рассуждения. Не снижай оценку за то, что студент не назвал конкретный пример, имя, число, дату, формулировку или порядок из текста темы, номер слайда или лекции, если суть верна. Правильная идея с неточностями — не ниже 1. Если сомневаешься между уровнями, выбирай более высокий.
Это устный экзамен: оценивай рассуждение, высказанное словами. Не требуй вычислений, формул, кода, схем, строгих определений и полного перечисления. Разговорная речь, оговорки, повторы и неточная терминология при верной сути — норма. Реплика распознана из речи и может содержать ошибки распознавания: не снижай за них оценку.
Каждый критерий: 0 — верного по существу нет; 1 — есть верная идея или направление рассуждения; 2 — суть показана, пусть неполно и с мелкими неточностями.
К1 — предметная корректность и владение терминологией.
К2 — логичность суждений и обоснованность выводов.
К3 — способность отвечать на возражения и рассматривать контрпримеры.
К4 — применение знания в изменённых условиях и понимание ограничений ответа.
К3 и К4 засчитывай за любое разумное рассуждение о возражении, другом случае или ограничении, даже короткое и без примера.
Уверенность, скорость речи и красноречие не оцениваются.
` + scope + `
verdict:
- "dont_know" — студент в последней реплике говорит, что не знает ответа (любыми словами);
- "insufficient" — последняя реплика не по теме или неразборчива, вывод сделать нельзя;
- "answered" — во всех остальных случаях.
evidence_lines — номера строк реплик студента, на которых основана оценка.
rationale — почему такая оценка, до 15 слов.
` + replyRules(r.Prerequisites) + `
reaction — спокойная нейтральная реакция экзаменатора на последнюю реплику студента: одно короткое предложение до 15 слов. Отметь, что сказано верно, и, если нужно, мягко назови, что можно добавить. Не критикуй и не оценивай студента: без слов «неверно», «неправильно», «ошибка», «ошибаешься», «не понял», без упрёков и восклицаний. Правильный ответ не раскрывай: по теме ещё могут быть вопросы.
explanation — суть правильного ответа по теме нейтральным тоном: одно предложение до 15 слов, без повтора реакции и без упрёка. Его скажут после реакции, когда тема закрыта.
Верни JSON: {"verdict":"answered","criteria":{"k1":0,"k2":0,"k3":0,"k4":0},"evidence_lines":[1],"rationale":"почему","reaction":"реплика","explanation":"как правильно"}`
}

// explanationPrompt asks for the correct answer after the student gave up.
func explanationPrompt(r application.EvaluationRequest) string {
	return topic(r.Node) + "\n" + dialogue(r.Dialogue) + `
Студент не знает ответа. Без упрёка объясни суть правильного ответа по теме: одно предложение до 15 слов.
` + replyRules(r.Prerequisites) + `
Верни JSON: {"text":"реплика"}`
}

// replyRules are the rules of Geek's reply to an answer. The next question is
// added after the reply, so the reply asks nothing; the prerequisites may be
// asked next, so the reply does not explain them.
func replyRules(prerequisites []string) string {
	rules := `Реплика обращена к студенту, без вопросов в конце: следующий вопрос Geek добавит сам. Не называй оценку и критерии. Студент не видит текст темы: не ссылайся на него.`
	if len(prerequisites) > 0 {
		rules += "\nНе объясняй эти темы: о них Geek может спросить следующими — " + strings.Join(prerequisites, "; ") + "."
	}
	return rules
}
